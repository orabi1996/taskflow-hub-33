import fs from "node:fs";
import path from "node:path";

const cwd = process.cwd();
const migrationsDir = path.join(cwd, "supabase", "migrations");
const outputFile = path.join(cwd, "supabase", "full_production_schema.sql");

console.log("\n========================================================");
console.log(" 📦 CRM-X Enterprise — Database Schema Bundler ");
console.log("========================================================\n");

if (!fs.existsSync(migrationsDir)) {
  console.error("❌ Error: supabase/migrations directory not found!");
  process.exit(1);
}

const files = fs
  .readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort(); // Natural chronological sort due to timestamp prefixes

console.log(`🔍 Discovered ${files.length} migration files in chronological sequence:\n`);

let combinedSQL = `-- ==============================================================================
-- CRM-X Enterprise — Unified Full Production Database Schema
-- Auto-generated by scripts/export-all-migrations.mjs
-- ==============================================================================
-- Instructions:
-- 1. Open your Supabase Dashboard: https://supabase.com/dashboard
-- 2. Navigate to SQL Editor -> New Query
-- 3. Paste and run this entire file to initialize or upgrade your database.
-- ==============================================================================

`;

for (const file of files) {
  const filePath = path.join(migrationsDir, file);
  const content = fs.readFileSync(filePath, "utf-8");
  console.log(`  + Bundling: ${file} (${(content.length / 1024).toFixed(1)} KB)`);

  combinedSQL += `\n-- ------------------------------------------------------------------------------\n`;
  combinedSQL += `-- Migration: ${file}\n`;
  combinedSQL += `-- ------------------------------------------------------------------------------\n\n`;
  combinedSQL += content.trim();
  combinedSQL += `\n\n`;
}

fs.writeFileSync(outputFile, combinedSQL, "utf-8");

const stats = fs.statSync(outputFile);
console.log(`\n✅ Generated unified production schema:`);
console.log(`   Path: ${outputFile}`);
console.log(`   Size: ${(stats.size / 1024).toFixed(1)} KB across ${files.length} migrations.\n`);
